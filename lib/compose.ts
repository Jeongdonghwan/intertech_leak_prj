export interface Composed {
  title: string; description: string; eyebrow: string; lead: string; answer: string;
  summary: [string, string][];
  region: { heading: string; paras: string[]; spots: string[] };
  service: { heading: string; paras: string[]; list: { title: string; items: string[] } };
  mod: { heading: string; paras: string[]; table?: [string, string][] };
  types: { heading: string; rows: { name: string; where: string; check: string }[]; text: string };
  signs: { heading: string; items: string[] };
  steps: { k: string; text: string }[];
  stepsHeading: string;
  photos: { p: Photo; caption: string }[];
  faq: { q: string; a: string }[];
  closing: { heading: string; text: string };
  cta: string;
  wl: string;
  branch: Branch;
}

