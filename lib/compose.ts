const fill = (s: string, v: Record<string, string>) => s.replace(/\{(\w+)(?::([가-힣]+))?\}/g, (_, k, js) => (js ? j(v[k] ?? '', js) : v[k] ?? ''));

export function compose(p: Page): Composed {
  const P = PLACES[p.place];
  const G: Gu = GUS[p.gu];
  const b = BRANCHES[p.branch];
  const w = W[p.word];
  const m = M[p.mod] || M[''];
  const s = p.slug;
  const wl = w.label;
  const placeName = P.name;
  const v: Record<string, string> = {
    kw: p.kw, w: wl, place: P.name, branch: b.name, brand: BRAND, branchAt: branchAt(b),
    answer: pick(w.answer, s, 'ans'),
  };
  const F = (t: string) => fill(t, v);

  const answer = v.answer;
  let title = F(pick(m.title, s, 'title'));
  if (title.length > 60) title = `${p.kw} | ${BRAND}`;
  let description = F(m.desc);
  if (description.length > 158) description = description.slice(0, 155).replace(/\s\S*$/, '') + '…';

  const lead = pick([
    `${placeName} ${wl} 상담은 ${b.name}(${b.phone})이 받습니다. ${HOURS}로 운영하며, 탐지·원인·공사·확인 순서로 진행합니다.`,
    `${j(wl, '는')} ${w.focus}입니다. ${j(placeName, '은')} ${BRAND} ${b.name} 담당이고 ${HOURS} 전화를 받습니다.`,
    `${placeName}에서 ${j(wl, '을')} 찾는 분께 — ${b.name}이 ${HOURS} 접수하고, 위치를 먼저 확인한 뒤 필요한 곳만 엽니다.`,
  ], s, 'lead');

  // 지역
  const regionParas = [
    pick([
      `${j(placeName, '은')} ${G.full}에 속합니다. ${P.note}`,
      `${P.note} 행정구역으로는 ${G.full}입니다.`,
    ], s, 'rg1'),
    P.unit === '구' || P.unit === '시·군' ? G.note : pick([`${G.full} 전체로 보면 ${G.note}`, `${G.note.split('. ')[0]}. ${placeName}도 그 흐름 안에 있습니다.`], s, 'rg2'),
    pick(BUILDING[P.ctx].text, s, 'bd'),
    pick([
      `${j(placeName, '은')} ${branchAt(b)}에서 맡습니다. ${b.name} 소개 원문에 적힌 출동 범위는 '${b.area}'입니다.`,
      `담당은 ${b.name}입니다. ${b.addr}에 있고, 소개 원문 기준 담당 범위는 '${b.area}'입니다.`,
      `${b.name}(${b.addr.replace(/^경기 /, '')})이 ${placeName} 상담과 방문을 맡습니다.`,
    ], s, 'rg4'),
  ];
  const region = {
    heading: pick([`${placeName} ${wl} 현장 특징`, `${placeName}의 건물과 ${wl}`, `${placeName} 주변 건물과 배관`], s, 'rh'),
    paras: regionParas,
    spots: P.spots,
  };

  const service = {
    heading: pick(w.heading, s, 'sh').replace('{w}', `${placeName} ${wl}`),
    paras: w.paras.map((alts, i) => pick(alts, s, `sp${i}`)),
    list: w.list,
  };
  const mod = {
    heading: F(pick(m.heading, s, 'mh')),
    paras: m.paras.map((alts, i) => F(pick(alts, s, `mp${i}`))),
    table: m.table ? pickN(m.table, 4, s, 'mt') : undefined,
  };

  const typeKeys = [...w.types, ...(P.ctx === 'rural' ? ['야외'] : P.ctx === 'apt' ? ['공용배관'] : ['벽간'])];
  const uniq = Array.from(new Set(typeKeys)).slice(0, 4);
  const types = {
    heading: pick([`${wl}과 가까운 누수 유형`, `${placeName}에서 자주 보는 유형`, `${wl}, 유형별로 보는 곳`], s, 'th').replace(`${wl}과`, j(wl, '과')),
    rows: uniq.map((k) => TYPES[k]),
    text: `용인점 플레이스 소개에 적힌 건물은 아파트·상가·빌라·주택·야외, 누수 유형은 층간·벽간·화장실·바닥·공용배관·노후배관·보일러입니다. ${placeName}처럼 ${BUILDING[P.ctx].kinds}가 많은 곳에서 ${wl}과 이어지는 유형을 골랐습니다.`.replace(`${wl}과 이어지는`, `${j(wl, '과')} 이어지는`),
  };

  const signs = {
    heading: pick([`이런 증상이 있으면 확인이 필요합니다`, `${placeName}에서 접수되는 ${wl} 관련 증상`, `확인이 필요한 신호`, `${placeName} 상담에서 자주 듣는 증상`], s, 'sg'),
    items: pickN(w.signs, 4, s, 'sg2').concat(pick([
      ['천장이나 벽 얼룩 테두리가 점점 커진다'], ['젖은 자리 주변에서 곰팡이 냄새가 난다'], ['물을 쓰지 않는 밤에도 물소리가 들린다'], ['장판을 들추면 아래가 젖어 있다'],
    ], s, 'sg3')),
  };

  const stepNames = ['탐지', '원인', '공사', '확인'];
  const steps = stepNames.map((k, i) => ({ k, text: w.step[i] }));

  const photos = photosFor(p, 3).map((ph) => ({ p: ph, caption: ph.scene }));

  const faq = [
    ...w.faq.map((f) => ({ q: F(f.q), a: F(f.a) })),
    ...m.faq.map((f) => ({ q: F(f.q), a: F(f.a) })),
    pick(GENERAL_FAQ, s, 'gf'),
  ];

  const summary: [string, string][] = [
    ['지역', `${G.full}${P.unit === '구' || P.unit === '시·군' ? '' : ' ' + P.name}`],
    ['담당', `${b.name} ${b.phone}`],
    ['운영', HOURS],
    ['진행', '탐지 → 원인 → 공사 → 확인'],
  ];

  const closing = {
    heading: pick([`${placeName} ${wl}, 젖은 자리와 시점을 알려 주세요`, `${b.name}이 ${placeName} 현장을 봅니다`, `${placeName}에서 물이 샐 때 연락처`], s, 'cl').replace(`${b.name}이`, j(b.name, '이')),
    text: pick([
      `언제부터 어디가 젖는지, 물을 쓰지 않을 때도 젖는지만 알려 주시면 통화에서 의심 계통을 먼저 좁힙니다. ${b.name} ${b.phone}, ${HOURS}.`,
      `${b.name}은 ${b.addr}에 있습니다. 접수는 ${HOURS}이고, 방문 예약도 됩니다.`,
      `계량기 사진과 젖은 자리 사진이 있으면 통화가 짧아집니다. ${b.name} ${b.phone}으로 연락 주세요.`,
    ], s, 'clt'),
  };
  const cta = pick([
    `${placeName} 담당 ${b.name} — 증상과 건물 형태를 먼저 들려주세요.`,
    `${b.name}은 ${HOURS} 전화를 받습니다. 메인 밸브를 잠근 뒤 연락 주세요.`,
    `물이 새는 시점과 위치를 알려 주시면 확인할 계통부터 정합니다.`,
  ], s, 'cta');

  return {
    title, description, eyebrow: `${G.full} · ${b.name} 담당`, lead, answer, summary, region, service, mod, types, signs,
    steps, stepsHeading: pick([`${wl} 진행 순서`, `${placeName} ${wl}, 네 단계로 봅니다`, `탐지에서 확인까지`], s, 'sth'),
    photos, faq, closing, cta, wl: w.type, branch: b,
  };
}

